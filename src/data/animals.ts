export function evaluateTraitQuestion(
  animal: AnimalDef,
  category: QuestionCategoryId,
  option: AnimalTraitOption
): boolean {
  switch (category) {
    case 'color':
      return animal.traits.color === option;
    case 'home':
      return animal.traits.home === option;
    case 'legs':
      return animal.traits.legs === option;
    case 'bodyCovering':
      return animal.traits.bodyCovering === option;
    case 'features':
      return animal.traits.features.includes(option as AnimalFeature);
    case 'pattern':
      return animal.traits.pattern === option;
  }
}
